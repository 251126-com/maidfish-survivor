import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args:['--no-sandbox','--disable-dev-shm-usage'] });
const page = await b.newPage({ viewport:{width:1280,height:720} });
await page.goto('http://127.0.0.1:4173/', {waitUntil:'load'});
await page.waitForTimeout(1200);
await page.mouse.click(640,230);
await page.waitForTimeout(1200);
const r = await page.evaluate(()=>{
  const s = window.__game.scene.getScene('Game');
  s.spawnTimer=99999; s.player.stats.hp=9999; s.player.stats.maxHp=9999; s.player.invuln=0;
  s.paused = true; s.elapsed = 600; s.bossSpawned = false;
  s.updateSpawner(0.016);
  const br = s.bossBrain;
  const ownNames = Object.getOwnPropertyNames(br).filter(n=>/pick|skill/i.test(n));
  const protoNames = Object.getOwnPropertyNames(Object.getPrototypeOf(br)).filter(n=>/pick|step/i.test(n));
  const before = { ownPick: ownNames, protoPick: protoNames, typePick: typeof br.pickSkill, isOwn: Object.prototype.hasOwnProperty.call(br,'pickSkill') };
  br.pickSkill = () => 'circle';
  const after = { typePick: typeof br.pickSkill, isOwn: Object.prototype.hasOwnProperty.call(br,'pickSkill'), call: br.pickSkill(), callName: br.pickSkill.name };
  return { before, after };
});
console.log(JSON.stringify(r));
await b.close();
